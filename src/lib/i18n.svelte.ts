export type Locale = 'zh' | 'en'
export type Key = keyof typeof en

const dicts: Record<Locale, Record<string, string>> = { en, zh }

let current = $state<Locale>('zh')

export function setLocale(l: Locale) {
  current = l
}
export function getLocale(): Locale {
  return current
}

/** The UI language the OS/browser asks for — zh for any Chinese locale, en
 *  otherwise. Resolves the "follow system" language preference. */
export function systemLocale(): Locale {
  const langs =
    typeof navigator !== 'undefined'
      ? (navigator.languages?.[0] ?? navigator.language ?? '')
      : ''
  return langs.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

/** Translate a key with optional params. Supports named placeholders ({name})
 * and the arb positional style ({arg1}, {arg2}, … in declared order). */
export function t(
  key: Key | string,
  params?: Record<string, string | number>,
): string {
  let s = dicts[current][key] ?? dicts.en[key] ?? key
  if (params) {
    const vals = Object.values(params)
    s = s.replace(/\{arg(\d+)\}/g, (_, d) => String(vals[Number(d) - 1] ?? ''))
    for (const [k, v] of Object.entries(params)) {
      s = s.replaceAll(`{${k}}`, String(v))
    }
  }
  return s
}
